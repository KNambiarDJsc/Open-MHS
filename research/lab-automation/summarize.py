"""PASS / FAIL / NOT_TESTED, per property and ecosystem, from a results directory's raw files.

    python summarize.py results/<label>

Writes SUMMARY.json and SUMMARY.md next to the evidence. The output depends only on the files:
sorted, with no clock, so the same evidence always gives the same bytes. A scenario that passed in
one run and failed in another is FAIL, with both counted. Nothing absent is shown as a pass.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

OUTCOMES = ("PASS", "FAIL", "NOT_TESTED")


def load(path: Path) -> dict | list | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def merge(into: dict, key: tuple[str, str], outcome: str) -> None:
    counts = into.setdefault(key, dict.fromkeys(OUTCOMES, 0))
    counts[outcome] += 1


def verdict(counts: dict[str, int]) -> str:
    if counts["FAIL"]:
        return "FAIL"
    if counts["PASS"]:
        return "PASS"
    return "NOT_TESTED"


def scan(root: Path) -> dict:
    gaps: dict = {}
    scenarios: dict = {}
    conformance: list = []
    for path in sorted(root.glob("gaps*/gaps-*.json")):
        doc = load(path)
        if doc:
            label = doc["ecosystem"] if path.parent.name == "gaps" else f"{doc['ecosystem']} ({path.parent.name[5:]})"
            for sid, r in doc["scenarios"].items():
                merge(gaps, (sid, label), r["outcome"])
    for path in sorted(root.glob("scenarios/*.json")):
        doc = load(path)
        if doc:
            ecosystem = path.stem.rsplit("-", 1)[0]
            for sid, r in doc["scenarios"].items():
                merge(scenarios, (ecosystem, sid), r["outcome"])
    for path in sorted(root.glob("conformance/*/*.json")):
        doc = load(path)
        if doc:
            subject = doc.get("subject", {})
            checks = doc.get("checks", [])
            count = {s: sum(c.get("status") == s for c in checks)
                     for s in ("pass", "fail", "untested", "not_applicable")}
            conformance.append({"run": path.parent.name, "device": subject.get("device") or path.stem,
                                "adapter": subject.get("adapter"), "reached": doc.get("achieved"),
                                "sources": subject.get("sources"), **count})
    steps = []
    for path in sorted(root.glob("steps/*.json")):
        steps.extend(load(path) or [])
    not_tested = sorted({(s["stage"], s["ecosystem"], s["why"]) for s in steps if s["outcome"] == "NOT_TESTED"})
    return {"gaps": gaps, "scenarios": scenarios, "conformance": conformance, "not_tested": not_tested,
            "failed_steps": [s for s in steps if s["outcome"] == "FAIL"]}


def to_markdown(data: dict) -> str:
    out = ["# Lab-automation results", "",
           "Generated by `summarize.py` from the raw files beside it. **Simulated; no physical effect is claimed.** "
           "Cells count runs as passed/total. A dash means this combination was not run: a gap, not a pass.", ""]
    ecos = sorted({k[1] for k in data["gaps"]})
    sids = sorted({k[0] for k in data["gaps"]})
    if sids:
        out += ["## Contract properties, by ecosystem", "", "| Property | " + " | ".join(ecos) + " |",
                "|---|" + "---|" * len(ecos)]
        for sid in sids:
            cells = []
            for eco in ecos:
                c = data["gaps"].get((sid, eco))
                if not c:
                    cells.append("—")
                else:
                    total = sum(c.values())
                    cells.append(f"{verdict(c)} {c['PASS']}/{total}")
            out.append(f"| {sid} | " + " | ".join(cells) + " |")
        out.append("")
    if data["conformance"]:
        out += ["## Conformance", "", "| Run | Device | Reached | pass | fail | untested | n/a |",
                "|---|---|---|---|---|---|---|"]
        for c in data["conformance"]:
            out.append(f"| {c['run']} | {c['device']} | {c['reached']} | {c['pass']} | {c['fail']} | {c['untested']} "
                       f"| {c['not_applicable']} |")
        out.append("")
    if data["scenarios"]:
        out += ["## Experiment scenarios", "", "| Ecosystem | Scenario | Result | Passed/total |", "|---|---|---|---|"]
        for (eco, sid), c in sorted(data["scenarios"].items()):
            out.append(f"| {eco} | {sid} | {verdict(c)} | {c['PASS']}/{sum(c.values())} |")
        out.append("")
    if data["not_tested"]:
        out += ["## Not tested in these runs", ""]
        out += [f"- **{stage}, {eco}:** {why}" for stage, eco, why in data["not_tested"]]
        out.append("")
    if data["failed_steps"]:
        out += ["## Steps that failed", ""]
        out += [f"- {s['stage']} {s['ecosystem']} {s.get('name', '')}: exit {s.get('exit')}"
                for s in data["failed_steps"]]
        out.append("")
    return "\n".join(out)


def main() -> int:
    root = Path(sys.argv[1])
    data = scan(root)
    plain = {**data,
             "gaps": {f"{k[0]}|{k[1]}": {**v, "verdict": verdict(v)} for k, v in sorted(data["gaps"].items())},
             "scenarios": {f"{k[0]}|{k[1]}": {**v, "verdict": verdict(v)} for k, v in sorted(data["scenarios"].items())}}
    (root / "SUMMARY.json").write_text(json.dumps(plain, indent=1) + "\n", encoding="utf-8", newline="\n")
    text = to_markdown(data)
    (root / "SUMMARY.md").write_text(text, encoding="utf-8", newline="\n")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

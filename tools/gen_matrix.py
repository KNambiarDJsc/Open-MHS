"""Generate the compatibility matrix from the registry and the conformance reports.

Writes docs/compatibility.md and the table between the matrix markers in README.md.
With --check, writes nothing and fails if either is out of date, so CI catches a report
or registry change that did not regenerate the matrix.

The matrix only restates what the reports say:

- "Pass" needs a passing report with nothing failed and nothing skipped (untested);
- simulation is never shown as physical validation;
- an entry without a report is "Not verified", whatever it claims;
- old reports are kept, listed, and never rewritten.

Usage: python tools/gen_matrix.py [--check]   (requires: pip install jsonschema)
"""
import pathlib
import sys

import registry_lib as lib

ROOT = lib.ROOT
DOC = ROOT / "docs" / "compatibility.md"
README = ROOT / "README.md"
BEGIN = "<!-- matrix:begin (generated by tools/gen_matrix.py; do not edit) -->"
END = "<!-- matrix:end -->"

EVIDENCE = {
    "simulated": "Simulated",
    "integration-tested": "Integration-tested (simulated peer)",
    "physically validated": "Physically validated",
    "unverified": "Not verified",
}
RESULT = {"pass": "Pass", "fail": "Fail", "incomplete": "Incomplete", "not verified": "Not verified"}
PROTOCOL = {
    "builtin": "built-in",
    "modbus-tcp": "Modbus TCP",
    "mqtt": "MQTT",
    "scpi": "SCPI",
    "http": "HTTP",
    "opc-ua": "OPC UA",
    "ros2": "ROS 2",
    "other": "other",
}
ORDER = {"official": 0, "community": 1, "experimental": 2, "unverified": 3}


def _link(label, path, prefix):
    return f"[{label}]({prefix}{path})"


def _source(entry, prefix):
    s = entry["source"]
    return _link(entry["id"], s if s.startswith("https://") else s, "" if s.startswith("https://") else prefix)


def _levels(entry, report):
    if report is None:
        declared = entry["conformance_profile"] or "none"
        return f"declares {declared}; none reached on file"
    reached = report.get("achieved") or "none"
    return f"{reached} (declares {report.get('declared') or 'none'})"


def _checks(report):
    s = report["summary"]
    return f"{s['pass']} pass, {s['fail']} fail, {s['untested']} skipped, {s['not_applicable']} n/a"


def rows(entries):
    return sorted(entries, key=lambda e: (ORDER[e["entry"]["category"]], e["entry"]["id"]))


def adapters_table(entries, prefix, compact):
    if compact:
        head = "| Adapter | Protocol | Evidence | Level reached | Result | Report |\n|---|---|---|---|---|---|\n"
    else:
        head = (
            "| Adapter | Protocol | Category | Evidence | Level reached | Result | Checks | "
            "Runtime | Platform | Verified | Report |\n|---|---|---|---|---|---|---|---|---|---|---|\n"
        )
    out = [head]
    for item in rows(entries):
        e, r = item["entry"], item["report"]
        evidence = EVIDENCE[lib.evidence_class(e, r)]
        result = RESULT[lib.result_of(r)]
        if r is None:
            report_cell = "none"
            runtime = platform = verified = checks = "-"
        else:
            report_cell = _link("report", e["report"]["path"], prefix)
            env = r.get("environment")
            runtime = env["runtime_version"] if env else "unknown"
            platform = lib.platform_of(r)
            verified = e["report"]["verified_at"]
            checks = _checks(r)
        if compact:
            out.append(
                f"| {_source(e, prefix)} | {PROTOCOL[e['protocol']]} | {evidence} | {_levels(e, r)} | {result} | {report_cell} |\n"
            )
        else:
            out.append(
                f"| {_source(e, prefix)} | {PROTOCOL[e['protocol']]} | {e['category']} | {evidence} | {_levels(e, r)} | "
                f"{result} | {checks} | {runtime} | {platform} | {verified} | {report_cell} |\n"
            )
    return "".join(out)


def history_table(reports, prefix):
    out = ["| Report | Adapter | Device | Suite | Runtime | Platform | Date | Declared | Reached | Sources |\n"
           "|---|---|---|---|---|---|---|---|---|---|\n"]
    for path, r in sorted(reports, key=lambda x: x[0]):
        env = r.get("environment")
        out.append(
            f"| {_link(pathlib.PurePosixPath(path).name, path, prefix)} | {r['subject']['adapter']} | "
            f"{r['subject'].get('device', '-')} | {r['suite_version']} | {env['runtime_version'] if env else 'unknown'} | "
            f"{lib.platform_of(r)} | {r['started_at'][:10]} | {r.get('declared') or 'none'} | {r.get('achieved') or 'none'} | "
            f"{', '.join(r['subject']['sources']) or 'none'} |\n"
        )
    return "".join(out)


def document(entries, reports):
    return f"""# Compatibility matrix

<!-- Generated by tools/gen_matrix.py from registry/adapters/ and conformance/reports/. Do not edit. -->

*Generated file. Edit the registry entries or add a conformance report, then run
`python tools/gen_matrix.py`. CI fails if this page is stale.*

This page restates what conformance reports say about each adapter. It is **evidence about
behaviour under test, not a safety certification**, and not an endorsement of any adapter.

**No adapter has been run against physical hardware by the project.** Every report below
was produced against a simulator, so no row says "Physically validated".

## How to read it

| Term | Meaning |
|---|---|
| Simulated | Tested against the project's in-process virtual lab. There is no wire protocol. |
| Integration-tested (simulated peer) | The adapter spoke its real protocol, over real sockets or pipes, to a simulated device. Consistent with itself; not proven against any particular real device. |
| Physically validated | A passing report whose readings came from a real device, not a simulator. Needs a report with no `simulator` source. |
| Not verified | No conformance report is on file. Whatever the entry claims is unchecked. |
| Level reached | The highest level whose checks all passed. Levels are cumulative. See [spec/conformance.md](../spec/conformance.md). |
| Result | **Pass** needs a passing report with nothing failed and nothing skipped. **Incomplete** means mandatory checks were skipped (untested). **Fail** means a check failed. |

Categories: **official** (maintained here), **community** (maintained elsewhere, with a
report), **experimental** (partial or lacking full evidence), **unverified** (listed without
evidence). See [registry/README.md](../registry/README.md).

## Adapters

{adapters_table(entries, "../", False)}
## Reports on file

Reports are never overwritten or deleted: a new run adds a file, and an entry above points
at the one it stands on (pinned by SHA-256).

{history_table(reports, "../")}"""


def readme_block(entries):
    return (
        f"{BEGIN}\n"
        "| Adapter | Protocol | Evidence | Level reached | Result | Report |\n"
        "|---|---|---|---|---|---|\n"
        + "".join(adapters_table(entries, "", True).splitlines(keepends=True)[2:])
        + f"{END}"
    )


def main(argv):
    check = "--check" in argv
    entries, problems = lib.load_entries()
    reports, report_problems = lib.all_reports()
    problems += report_problems
    if problems:
        print("registry or reports are invalid; not generating:\n" + "\n".join(problems))
        return 1

    want_doc = document(entries, reports)
    text = README.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print("README.md has no matrix markers")
        return 1
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    want_readme = head + readme_block(entries) + tail

    have_doc = DOC.read_text(encoding="utf-8") if DOC.exists() else None
    if check:
        stale = []
        if have_doc != want_doc:
            stale.append(str(DOC.relative_to(ROOT)))
        if text != want_readme:
            stale.append("README.md")
        if stale:
            print("stale: " + ", ".join(stale) + "\nrun: python tools/gen_matrix.py")
            return 1
        print("ok: compatibility matrix is current")
        return 0

    DOC.write_text(want_doc, encoding="utf-8", newline="\n")
    README.write_text(want_readme, encoding="utf-8", newline="\n")
    print(f"wrote {DOC.relative_to(ROOT)} and the matrix in README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
